#include <iostream>
using namespace std;

int main() {
    cout << "Hello, World!" << endl;

    // Simple variable test
    int a = 5;
    int b = 10;
    cout << "Sum of a and b: " << (a + b) << endl;

    // Loop test
    cout << "Counting from 1 to 5:" << endl;
    for (int i = 1; i <= 5; i++) {
        cout << i << " ";
    }
    cout << endl;

    return 0;
}
